def normalize_lang_code(raw: str) -> str:
    """Normalize an OS locale string or env value into ('ko', 'en', 'ja', 'zh')."""
    if not raw:
        return ""
    token = str(raw).strip().split(".")[0].split("@")[0].lower()
    if token in ("", "c", "posix"):
        return ""
    if token.startswith("ko") or "korean" in token:
        return "ko"
    if token.startswith("ja") or token.startswith("jp") or "japanese" in token:
        return "ja"
    if token.startswith("zh") or "chinese" in token:
        return "zh"
    if token.startswith("en") or "english" in token:
        return "en"
    # Unsupported locales default to English
    return "en"


def _detect_windows_ui_language() -> str:
    try:
        lcid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        primary = lcid & 0x3FF
        if primary == 0x12:
            return "ko"
        if primary == 0x11:
            return "ja"
        if primary == 0x04:
            return "zh"
        if primary == 0x09:
            return "en"
        win_loc = locale.windows_locale.get(lcid, "")
        return normalize_lang_code(win_loc) or "en"
    except Exception:
        return ""


def _detect_macos_ui_language() -> str:
    try:
        out = subprocess.check_output(
            ["defaults", "read", "-g", "AppleLanguages"],
            text=True,
            timeout=1.5,
            stderr=subprocess.DEVNULL,
        )
        for line in out.splitlines():
            cleaned = line.strip().strip('",();')
            norm = normalize_lang_code(cleaned)
            if norm:
                return norm
    except Exception:
        pass
    return ""


def detect_system_language() -> str:
    """
    Detect active OS / sandbox system language cleanly across Windows, macOS, and Linux.
    Checks standard POSIX/sandbox overrides (LIFE_OS_LANG, LC_ALL, LC_MESSAGES, LANGUAGE, LANG)
    first so isolated sandbox tests and Linux/macOS containers work deterministically.
    """
    for env_key in ("LIFE_OS_LANG", "LC_ALL", "LC_MESSAGES", "LANGUAGE", "LANG"):
        val = os.environ.get(env_key, "").strip()
        if not val:
            continue
        first = val.split(":")[0].strip()
        norm = normalize_lang_code(first)
        if norm:
            return norm

    if sys.platform.startswith("win"):
        win_lang = _detect_windows_ui_language()
        if win_lang:
            return win_lang
    elif sys.platform == "darwin":
        mac_lang = _detect_macos_ui_language()
        if mac_lang:
            return mac_lang

    try:
        loc_lang = locale.getlocale()[0]
        norm = normalize_lang_code(loc_lang)
        if norm:
            return norm
    except Exception:
        pass

    return "en"


def resolve_language(setting_val: str = None) -> str:
    """Resolve explicit user language setting or 'auto' -> detected system language."""
    if setting_val:
        low = str(setting_val).strip().lower()
        if low in SUPPORTED_LANGUAGES:
            return low
    return detect_system_language()


