def tr(key: str, lang: str = None, /, **kwargs) -> str:
    """Look up localized text string with safe fallback to English and key name."""
    resolved = resolve_language(lang)
    table = TRANSLATIONS.get(resolved) or TRANSLATIONS["en"]
    template = table.get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template


def get_language_options(lang: str = None) -> list:
    """Return [(display_label, code)] pairs for Settings language dropdown."""
    resolved = resolve_language(lang)
    sys_lang = detect_system_language()
    sys_name = LANGUAGE_LABELS.get(sys_lang, sys_lang)
    auto_label = tr("lang_auto_label", resolved, lang_name=sys_name)
    return [("auto", auto_label)] + [(code, LANGUAGE_LABELS[code]) for code in SUPPORTED_LANGUAGES]
